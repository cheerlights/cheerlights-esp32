"""Generate test/test_profile/vectors.h from docs/ble-vectors.json and test/test_screen/vectors.h from
docs/colors.json, so the published files stay the source."""
import json
import os

try:
    Import("env")  # noqa: F821  PlatformIO provides this when run as an extra script
    root = env["PROJECT_DIR"]  # noqa: F821
except NameError:
    root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")

with open(os.path.join(root, "docs", "ble-vectors.json"), encoding="utf-8") as f:
    spec = json.load(f)


def arr(raw):
    return ", ".join(f"0x{b:02x}" for b in raw)


lines = [
    "// Generated by tools/gen_vectors.py from docs/ble-vectors.json. Do not edit.",
    "#pragma once",
    "#include <stdint.h>",
    "struct FrameVector {",
    "  const char* name; uint8_t bytes[10]; bool stale; uint8_t paletteIndex;",
    "  uint8_t r, g, b; uint16_t sequence; uint16_t ageMinutes;",
    "};",
    "static const FrameVector FRAME_VECTORS[] = {",
]
for v in spec["frame"]:
    raw = bytes.fromhex(v["bytes"])
    assert len(raw) == 10, v["name"]
    rgb = bytes.fromhex(v["rgb"])
    lines.append(
        f'  {{"{v["name"]}", {{{arr(raw)}}}, {str(v["stale"]).lower()}, {v["paletteIndex"]}, '
        f'{rgb[0]}, {rgb[1]}, {rgb[2]}, {v["sequence"]}, {v["ageMinutes"]}}},'
    )
lines += ["};", ""]

# Frames from a newer phone are longer; a reader takes the fields it knows.
lines += [
    "struct NewerFrameVector {",
    "  const char* name; uint8_t bytes[32]; uint8_t length; bool stale; uint8_t paletteIndex;",
    "  uint8_t r, g, b; uint16_t sequence; uint16_t ageMinutes;",
    "};",
    "static const NewerFrameVector FRAME_NEWER[] = {",
]
for v in spec["frameNewer"]:
    raw = bytes.fromhex(v["bytes"])
    assert 10 < len(raw) <= 32, v["name"]
    rgb = bytes.fromhex(v["rgb"])
    lines.append(
        f'  {{"{v["name"]}", {{{arr(raw)}}}, {len(raw)}, {str(v["stale"]).lower()}, {v["paletteIndex"]}, '
        f'{rgb[0]}, {rgb[1]}, {rgb[2]}, {v["sequence"]}, {v["ageMinutes"]}}},'
    )
lines += ["};", ""]

lines += [
    "struct LightVector { const char* name; uint8_t bytes[16]; uint8_t length; uint8_t brightness, effect, speed; };",
    "static const LightVector LIGHT_VECTORS[] = {",
]
for v in spec["light"] + spec["lightClamped"] + spec["lightNewer"]:
    raw = bytes.fromhex(v["bytes"])
    lines.append(f'  {{"{v["name"]}", {{{arr(raw)}}}, {len(raw)}, {v["brightness"]}, {v["effect"]}, {v["speed"]}}},')
lines += ["};", "static const LightVector LIGHT_REJECTED[] = {"]
for v in spec["lightRejected"]:
    raw = bytes.fromhex(v["bytes"])
    padded = raw + bytes(16 - len(raw))
    lines.append(f'  {{"{v["name"]}", {{{arr(padded)}}}, {len(raw)}, 0, 0, 0}},')
lines += ["};", ""]

# Info as each firmware writes it. needsSetup is absent before 0.4.0, and identify and the board before 0.5.0.
lines += [
    "struct InfoVector {",
    "  const char* name; uint8_t bytes[64]; unsigned length; uint8_t major, minor, patch;",
    "  bool display, offControl, light, needsSetup, identify; const char* board;",
    "};",
    "static const InfoVector INFO_VECTORS[] = {",
]
for v in spec["info"]:
    raw = bytes.fromhex(v["bytes"])
    assert len(raw) <= 64, v["name"]
    major, minor, patch = (int(x) for x in v["firmware"].split("."))
    flags = [v["display"], v["offControl"], v.get("light", False), v.get("needsSetup", False), v.get("identify", False)]
    board = '"' + v["board"] + '"' if "board" in v else "nullptr"
    lines.append(
        f'  {{"{v["name"]}", {{{arr(raw)}}}, {len(raw)}, {major}, {minor}, {patch}, '
        f'{", ".join(str(f).lower() for f in flags)}, {board}}},'
    )
lines += ["};"]
lines += ["struct IdentifyVector { const char* name; uint8_t bytes[4]; unsigned length; bool ok; };",
          "static const IdentifyVector IDENTIFY_VECTORS[] = {"]
for v, ok in [(v, True) for v in spec["identify"]] + [(v, False) for v in spec["identifyRejected"]]:
    raw = bytes.fromhex(v["bytes"])
    lines.append(f'  {{"{v["name"]}", {{{arr(raw + bytes(4 - len(raw)))}}}, {len(raw)}, {str(ok).lower()}}},')
lines += ["};"]
effects = bytes.fromhex(spec["effects"][0]["bytes"])
lines += [
    f"static const uint8_t EFFECTS_VECTOR[] = {{{arr(effects)}}};",
    f"static const unsigned EFFECTS_VECTOR_LENGTH = {len(effects)};",
    "",
]
out = os.path.join(root, "test", "test_profile", "vectors.h")
os.makedirs(os.path.dirname(out), exist_ok=True)
with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(lines))


with open(os.path.join(root, "docs", "colors.json"), encoding="utf-8") as f:
    palette = json.load(f)["colors"]

lines = [
    "// Generated by tools/gen_vectors.py from docs/colors.json. Do not edit.",
    "#pragma once",
    "#include <stdint.h>",
    "struct PaletteVector { unsigned index; const char* name; const char* hex; uint8_t r, g, b; bool whiteText; };",
    "static const PaletteVector PALETTE_VECTORS[] = {",
]
for c in palette:
    rgb = bytes.fromhex(c["hex"].lstrip("#"))
    assert c["text"] in ("black", "white"), c["name"]
    lines.append(
        f'  {{{c["index"]}, "{c["name"]}", "{c["hex"]}", {rgb[0]}, {rgb[1]}, {rgb[2]}, '
        f'{str(c["text"] == "white").lower()}}},'
    )
lines += ["};", f"static const unsigned PALETTE_VECTOR_COUNT = {len(palette)};", ""]
out = os.path.join(root, "test", "test_screen", "vectors.h")
os.makedirs(os.path.dirname(out), exist_ok=True)
with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(lines))
