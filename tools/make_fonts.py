"""Write lib/screen/fonts.cpp: Source Sans 3 as anti-aliased glyphs, 16 levels of coverage per pixel.

    python tools/make_fonts.py

Needs Pillow. The output is committed, so a build does not need Python packages; run this again only to change
a size or the characters. Glyphs are printable ASCII. Each pixel is 4 bits, two to a byte, row by row.
"""
import os

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
FIRST, LAST = 32, 126
# name in the code, file, pixel size
FONTS = [
    ("FONT_NAME", "SourceSans3-Bold.ttf", 46),
    ("FONT_TITLE", "SourceSans3-Bold.ttf", 24),
    ("FONT_TEXT", "SourceSans3-Regular.ttf", 18),
]


def glyphs(path, size):
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    out = []
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        advance = round(font.getlength(ch))
        x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        alpha = []
        if w and h:
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
            px = img.load()
            for y in range(h):
                for x in range(w):
                    alpha.append((px[x, y] * 15 + 127) // 255)
        out.append({"w": w, "h": h, "left": x0, "top": -y0, "advance": advance, "alpha": alpha})
    return out, ascent, descent


def main():
    lines = [
        "// Generated by tools/make_fonts.py from fonts/SourceSans3-*.ttf (SIL Open Font License 1.1). Do not edit.",
        '#include "fonts.h"',
        "",
        "namespace cheerlights {",
        "",
    ]
    for name, file, size in FONTS:
        table, ascent, descent = glyphs(os.path.join(ROOT, "fonts", file), size)
        data = []
        rows = []
        for g in table:
            offset = len(data)
            a = g["alpha"]
            for i in range(0, len(a), 2):
                hi = a[i]
                lo = a[i + 1] if i + 1 < len(a) else 0
                data.append((hi << 4) | lo)
            rows.append(f"    {{{offset}, {g['w']}, {g['h']}, {g['left']}, {g['top']}, {g['advance']}}},")
        key = name.lower()
        lines.append(f"// {file} at {size} px")
        lines.append(f"static const uint8_t {key}_alpha[] = {{")
        for i in range(0, len(data), 24):
            lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
        lines.append("};")
        lines.append(f"static const Glyph {key}_glyphs[] = {{")
        lines += rows
        lines.append("};")
        lines.append(f"const Font {name} = {{{key}_alpha, {key}_glyphs, {FIRST}, {LAST}, {ascent}, {descent}}};")
        lines.append("")
    lines.append("}  // namespace cheerlights")
    lines.append("")
    out = os.path.join(ROOT, "lib", "screen", "fonts.cpp")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print("wrote", out, os.path.getsize(out), "bytes")


if __name__ == "__main__":
    main()
